"""Jewbuntu APT repository enrollment.

The sources file is generated (not a package conffile) because it must be
rewritten for the running Ubuntu codename after a release upgrade, which
Ubuntu's upgrader may have disabled. Enrollment refuses any codename that is
not in the support matrix, so a new OS is never pointed at packages built
for the old one.

Layout (see repository/README.md):
  <url>/dists/<codename>/main          stable channel
  <url>/dists/<codename>-testing/main  testing channel
Trust is scoped with Signed-By to the Jewbuntu keyring only, and an APT
preferences file stops this origin from replacing non-Jewbuntu packages.
"""

import os
from pathlib import Path

from . import paths
from .doctor import platform_report
from .upgrade import load_matrix, matrix_entry

SOURCES_FILE = Path(os.environ.get("JEWBUNTU_APT_SOURCES", "/etc/apt/sources.list.d/jewbuntu.sources"))
PREFS_FILE = Path(os.environ.get("JEWBUNTU_APT_PREFS", "/etc/apt/preferences.d/jewbuntu.pref"))
KEYRING = "/usr/share/keyrings/jewbuntu-archive-keyring.gpg"
REPO_CONF = paths.SYSTEM_CONFIG_DIR / "repository.conf"

PREFS = """# Generated by jewbuntu repo enroll. Restricts the Jewbuntu origin to its own
# package namespace so it can never override Ubuntu packages.
Package: jewbuntu-*
Pin: release o=Jewbuntu
Pin-Priority: 500

Package: *
Pin: release o=Jewbuntu
Pin-Priority: -1
"""


def read_repo_conf():
    conf = {"url": "", "channel": "stable"}
    if REPO_CONF.exists():
        for line in REPO_CONF.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                conf[k.strip()] = v.strip()
    return conf


def render_sources(url, codename, channel):
    suite = codename if channel == "stable" else f"{codename}-{channel}"
    return (
        "# Generated by 'jewbuntu repo enroll'. Re-run after an Ubuntu release upgrade.\n"
        "Types: deb\n"
        f"URIs: {url}\n"
        f"Suites: {suite}\n"
        "Components: main\n"
        f"Signed-By: {KEYRING}\n"
    )


def status():
    plat = platform_report()
    codename = plat["os"].get("VERSION_CODENAME")
    entry = matrix_entry(load_matrix(), codename)
    current = SOURCES_FILE.read_text() if SOURCES_FILE.exists() else None
    enabled = None
    configured_suite = None
    if current is not None:
        enabled = "Enabled: no" not in current
        for line in current.splitlines():
            if line.startswith("Suites:"):
                configured_suite = line.split(":", 1)[1].strip()
    mismatch = bool(configured_suite and not configured_suite.split("-")[0] == codename)
    return {
        "codename": codename,
        "supported_entry": entry,
        "sources_file": str(SOURCES_FILE),
        "configured": current is not None,
        "enabled": enabled,
        "configured_suite": configured_suite,
        "suite_mismatch": mismatch,
        "keyring_present": Path(KEYRING).exists(),
        "repo_conf": read_repo_conf(),
    }


def enroll(channel=None, url=None, dry_run=False):
    conf = read_repo_conf()
    url = url or conf.get("url")
    channel = channel or conf.get("channel", "stable")
    st = status()
    entry = st["supported_entry"]
    if not url:
        raise SystemExit(f"No repository URL configured. Set url= in {REPO_CONF} (no public Jewbuntu repository exists yet).")
    if entry is None:
        raise SystemExit(f"Ubuntu '{st['codename']}' is not in the support matrix; refusing to enroll. Check for a Jewbuntu update that supports it.")
    if channel not in entry.get("channels", []):
        raise SystemExit(f"Channel '{channel}' is not offered for {st['codename']} (offered: {', '.join(entry.get('channels', []))}).")
    if not st["keyring_present"] and not dry_run:
        raise SystemExit(f"Keyring {KEYRING} is missing; install the Jewbuntu archive keyring first.")
    sources = render_sources(url, st["codename"], channel)
    if dry_run:
        return {"would_write": {str(SOURCES_FILE): sources, str(PREFS_FILE): PREFS}}
    if os.geteuid() != 0:
        raise SystemExit("Enrollment changes system APT configuration: run with sudo (or use --dry-run).")
    for path, text in ((SOURCES_FILE, sources), (PREFS_FILE, PREFS)):
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    return {"written": [str(SOURCES_FILE), str(PREFS_FILE)], "next": "sudo apt update && sudo apt install --only-upgrade 'jewbuntu-*'"}
